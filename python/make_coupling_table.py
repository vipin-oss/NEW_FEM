"""make_coupling_table.py -- Paper_12/table_coupling.tex (tabular body only)
from results/coupling_provenance.json.

Every coupling factor the paper quotes appears once, with its boundary
condition, mesh, electrode pair, matrix, formula and the entry of the JSON
archive that reproduces it.  The table float and the caption live in
sec/06_results.tex, so that check_float_order.py sees the label.
"""
from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "Paper_12")

SHORT = {
    "k2_free_nogradient_48x4": "free, no window",
    "k2_clamped_nogradient_48x4": "left edge clamped, no window",
    "k2_clamped_gradient_48x4": "clamped, window on",
    "k2_clamped_gradient_24x2": "clamped, window on, sweep mesh",
    "k2_mode_based_Kuu_24x2": "clamped, window on",
    "k2_mode_based_Ksc_24x2": "clamped, window on",
    "k2_mode_based_Ksc_24x2_mu0": "clamped, window on",
    "k2_closed_form_plane_stress": "none (constitutive tensors)",
}
MATRIX = {
    "k2_mode_based_Kuu_24x2": "$K_{oc}$ vs $K_{uu}$",
    "k2_mode_based_Ksc_24x2": "$K_{oc}$ vs $K_{sc}$",
    "k2_mode_based_Ksc_24x2_mu0": "$K_{oc}$ vs $K_{sc}$",
}
FORMULA = {
    "k2_mode_based_Kuu_24x2": "$(\\omega_{oc}^{2}-\\omega_{u}^{2})/\\omega_{oc}^{2}$",
    "k2_mode_based_Ksc_24x2": "$(\\omega_{oc}^{2}-\\omega_{sc}^{2})/\\omega_{oc}^{2}$",
    "k2_mode_based_Ksc_24x2_mu0": "$(\\omega_{oc}^{2}-\\omega_{sc}^{2})/\\omega_{oc}^{2}$",
}
MU = {
    "k2_free_nogradient_48x4": "$0$",
    "k2_clamped_nogradient_48x4": "$0$",
    "k2_clamped_gradient_48x4": "$0$",
    "k2_clamped_gradient_24x2": "$0$",
    "k2_mode_based_Kuu_24x2": "$10^{-6}$",
    "k2_mode_based_Ksc_24x2": "$10^{-6}$",
    "k2_mode_based_Ksc_24x2_mu0": "$0$",
    "k2_closed_form_plane_stress": "---",
}


def main():
    d = json.load(open(os.path.join(ROOT, "results",
                                    "coupling_provenance.json")))
    body = []
    for i, r in enumerate(d["rows"]):
        lab = r["label"]
        mesh = r["mesh"] if r["mesh"] != "--" else "---"
        body.append(" & ".join([
            "$%.5f$" % r["value"],
            SHORT[lab],
            mesh,
            MU[lab],
            MATRIX.get(lab, "$K_{sc}$"),
            FORMULA.get(lab, "$x/(1+x)$"),
            "\\texttt{rows[%d]}" % i,
        ]) + r" \\")
    tex = "\n".join([
        "% tabular body generated by python/make_coupling_table.py"
        " -- do not edit",
        r"\begin{tabular}{@{}r l l r l l r@{}}",
        r"\toprule",
        r"$k^2$ & boundary condition & mesh & $\mu$ (\si{\coulomb\per\metre})"
        r" & matrix & formula & entry \\",
        r"\midrule",
    ] + body + [
        r"\bottomrule",
        r"\end{tabular}",
        "",
    ])
    with open(os.path.join(OUT, "table_coupling.tex"), "w") as fh:
        fh.write(tex)
    print("  %d rows -> Paper_12/table_coupling.tex" % len(body))


if __name__ == "__main__":
    main()
